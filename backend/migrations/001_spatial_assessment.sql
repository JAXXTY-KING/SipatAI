CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS farm_parcels (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_dataset TEXT NOT NULL,
    source_parcel_id TEXT NOT NULL,
    barangay_name TEXT NOT NULL,
    crop_type TEXT,
    source_crs TEXT NOT NULL,
    geometry_crs TEXT NOT NULL DEFAULT 'EPSG:4326' CHECK (geometry_crs = 'EPSG:4326'),
    geom geometry(MultiPolygon, 4326) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT farm_parcels_source_identifier_unique
        UNIQUE (source_dataset, source_parcel_id),
    CONSTRAINT farm_parcels_valid_geometry CHECK (ST_IsValid(geom))
);

CREATE INDEX IF NOT EXISTS farm_parcels_geom_gix
    ON farm_parcels USING GIST (geom);

CREATE TABLE IF NOT EXISTS assessment_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name TEXT NOT NULL,
    municipality TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('processing', 'completed', 'failed')),
    model_version TEXT,
    source_crs TEXT NOT NULL,
    geometry_crs TEXT NOT NULL DEFAULT 'EPSG:4326' CHECK (geometry_crs = 'EPSG:4326'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    completed_at TIMESTAMPTZ,
    CONSTRAINT assessment_completed_timestamp_required
        CHECK (status <> 'completed' OR completed_at IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS flood_polygons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id BIGINT NOT NULL REFERENCES assessment_runs(id) ON DELETE CASCADE,
    geom geometry(MultiPolygon, 4326) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT flood_polygons_valid_geometry CHECK (ST_IsValid(geom))
);

CREATE INDEX IF NOT EXISTS flood_polygons_geom_gix
    ON flood_polygons USING GIST (geom);

CREATE TABLE IF NOT EXISTS parcel_damage_assessments (
    assessment_id BIGINT NOT NULL REFERENCES assessment_runs(id) ON DELETE CASCADE,
    parcel_id BIGINT NOT NULL REFERENCES farm_parcels(id),
    parcel_area_hectares NUMERIC(14, 4) NOT NULL CHECK (parcel_area_hectares > 0),
    flooded_area_hectares NUMERIC(14, 4) NOT NULL CHECK (flooded_area_hectares >= 0),
    damage_percent NUMERIC(5, 2) NOT NULL CHECK (damage_percent BETWEEN 0 AND 100),
    severity TEXT CHECK (severity IN ('Severe', 'Moderate', 'Light')),
    CONSTRAINT flooded_area_within_parcel CHECK (flooded_area_hectares <= parcel_area_hectares),
    PRIMARY KEY (assessment_id, parcel_id)
);

CREATE INDEX IF NOT EXISTS parcel_damage_assessments_assessment_idx
    ON parcel_damage_assessments (assessment_id);
